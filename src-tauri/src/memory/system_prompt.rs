use super::conversational_preferences::PreferencesStore;
use super::master_description::MasterDescriptionStore;

/// Собирает полный системный промпт из статических секций и данных из memory-подсистемы.
///
/// Порядок секций фиксирован. Секции 2 и 3 опциональны — если данных нет, модель получает
/// инструкцию собрать информацию.
pub fn assemble_system_prompt(
    master_store: &MasterDescriptionStore,
    prefs_store: &PreferencesStore,
) -> String {
    let parts: Vec<String> = vec![
        // ── 1. Этический кодекс (статичный) ──────────────────────────
        ETHICAL_CODEX.to_string(),
        // ── 2. Master description ────────────────────────────────────
        master_section(master_store),
        // ── 3. Conversational preferences ────────────────────────────
        preferences_section(prefs_store),
        // ── 4. Назначение memory-подсистемы ──────────────────────────
        MEMORY_PURPOSE.to_string(),
        // ── 5. Эпистемический статус фактов ──────────────────────────
        EPISTEMIC_STATUS.to_string(),
        // ── 6. Семантика foundation_changed ──────────────────────────
        FOUNDATION_CHANGED.to_string(),
        // ── 7. Семантика master description ──────────────────────────
        MASTER_SEMANTICS.to_string(),
        // ── 8. Семантика rewrite-тулов ───────────────────────────────
        REWRITE_SEMANTICS.to_string(),
        // ── 9. Мониторинг контекста ──────────────────────────────────
        CONTEXT_MONITORING.to_string(),
        // ── 10. Немедленная фиксация findings ────────────────────────
        IMMEDIATE_FINDINGS.to_string(),
        // ── 11. Housekeeping-процедура ───────────────────────────────
        HOUSEKEEPING.to_string(),
    ];

    parts.join("\n\n")
}

fn master_section(store: &MasterDescriptionStore) -> String {
    match store.read_optional() {
        Ok(Some((doc, foundation_changed))) => {
            let mut s = format!(
                "## Профиль пользователя (Master Description)\n\n{}\n\n---\n\nВерсия: {}. Создан: {}.",
                doc.content, doc.version, doc.created_at
            );
            if foundation_changed {
                s.push_str(
                    "\n\n**ВНИМАНИЕ: foundation_changed = true.** Факты, на которых основан этот профиль, были исправлены. Профиль может быть неактуальным. При первой возможности выполни housekeeping.",
                );
            }
            s.push_str("\n\nЭтот профиль — твоё навигационное оглавление. Он всегда в контексте. Используй его чтобы помнить, что ты уже знаешь о пользователе, и не переспрашивать известное.");
            s
        }
        Ok(None) => {
            "## Профиль пользователя (Master Description)\n\nПрофиль пользователя ещё не собран. Это новый пользователь. В диалоге собери информацию о пользователе: возраст, пол, вес, рост, цели по питанию, ограничения, аллергии, хронические состояния, лабораторные показатели. Фиксируй факты через `create_user_reported_fact`, находки через `create_finding`, а когда картина сложится — выполни housekeeping для создания Master Description."
                .to_string()
        }
        Err(e) => {
            format!("## Профиль пользователя (Master Description)\n\n(ошибка чтения профиля: {e})")
        }
    }
}

fn preferences_section(store: &PreferencesStore) -> String {
    match store.read_optional() {
        Ok(Some(prefs)) => {
            format!(
                "## Предпочтения пользователя\n\n{}\n\n---\n\nОбновлены: {}.\n\nСледуй этим предпочтениям в диалоге. Если пользователь корректирует твой стиль — обнови через `rewrite_conversational_preferences`.",
                prefs.content, prefs.updated_at
            )
        }
        Ok(None) => {
            "## Предпочтения пользователя\n\nПредпочтения пока не заданы. По умолчанию: отвечай на русском языке, стиль — экспертный, но доступный. Если пользователь высказывает предпочтения по стилю общения — зафиксируй через `rewrite_conversational_preferences`."
                .to_string()
        }
        Err(e) => {
            format!("## Предпочтения пользователя\n\n(ошибка чтения предпочтений: {e})")
        }
    }
}

